create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Normalise un texte pour la recherche (minuscules, sans accents).
create or replace function private.normalize_text(p text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(p, '')));
$$;

-- Limitation de débit générique (anti-spam / anti-abus).
create table private.rate_events (
  id bigint generated always as identity primary key,
  user_id uuid not null,
  kind text not null,
  created_at timestamptz not null default now()
);
create index rate_events_lookup_idx on private.rate_events (user_id, kind, created_at desc);

create or replace function private.enforce_rate_limit(p_kind text, p_max integer, p_window interval)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_count integer;
begin
  if v_uid is null then
    return;
  end if;
  select count(*) into v_count
  from private.rate_events
  where user_id = v_uid and kind = p_kind and created_at > now() - p_window;
  if v_count >= p_max then
    raise exception 'Trop de tentatives. Merci de patienter un peu avant de recommencer.'
      using errcode = 'P0429', hint = 'rate_limited';
  end if;
  insert into private.rate_events (user_id, kind) values (v_uid, p_kind);
end;
$$;

-- Nettoyage des anciens événements de limitation (appelé par la tâche planifiée).
create or replace function private.purge_rate_events()
returns void
language sql
security definer
set search_path = ''
as $$
  delete from private.rate_events where created_at < now() - interval '2 days';
$$;

