-- Vérifie que l'utilisateur courant est connecté et actif.
create or replace function private.require_active_user()
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_profile public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Vous devez être connecté.' using errcode = '28000';
  end if;
  select * into v_profile from public.profiles where id = auth.uid();
  if not found then
    raise exception 'Profil introuvable.' using errcode = 'P0002';
  end if;
  if v_profile.status <> 'active' then
    raise exception 'Votre compte est suspendu. Contactez l''équipe FenuaMatch.' using errcode = '42501';
  end if;
  return v_profile;
end;
$$;

-- Règles de nom d'utilisateur (format + noms réservés / inappropriés).
create or replace function private.username_problem(p_username text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v text := lower(coalesce(p_username, ''));
  v_flat text := regexp_replace(v, '[^a-z0-9]', '', 'g');
  v_word text;
  v_reserved text[] := array[
    'admin', 'administrateur', 'administrator', 'root', 'support', 'aide', 'help',
    'fenuamatch', 'fenua-match', 'fenua_match', 'moderateur', 'moderation', 'moderator',
    'staff', 'equipe', 'officiel', 'official', 'contact', 'securite', 'security',
    'system', 'systeme', 'null', 'undefined', 'api', 'www', 'mail', 'noreply', 'no-reply',
    'compte-supprime', 'supprime', 'anonyme'];
  v_forbidden text[] := array[
    'admin', 'fenuamatch', 'moderat', 'officiel', 'connard', 'salope', 'pute', 'encule',
    'nique', 'pede', 'batard', 'merde', 'nazi', 'hitler', 'fuck', 'bitch', 'shit', 'raciste'];
begin
  if v !~ '^[a-z0-9][a-z0-9_.-]{2,23}$' then
    return 'Le nom d''utilisateur doit contenir 3 à 24 caractères : lettres minuscules, chiffres, point, tiret ou tiret bas, et commencer par une lettre ou un chiffre.';
  end if;
  if v = any (v_reserved) then
    return 'Ce nom d''utilisateur est réservé.';
  end if;
  foreach v_word in array v_forbidden loop
    if position(v_word in v_flat) > 0 then
      return 'Ce nom d''utilisateur n''est pas autorisé.';
    end if;
  end loop;
  return null;
end;
$$;

-- Vérification publique (utilisée pendant l'inscription).
create or replace function public.check_username(p_username text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_problem text := private.username_problem(p_username);
begin
  if v_problem is not null then
    return v_problem;
  end if;
  if exists (select 1 from public.profiles where username = lower(p_username)::extensions.citext and id is distinct from auth.uid()) then
    return 'Ce nom d''utilisateur est déjà pris.';
  end if;
  return null;
end;
$$;

-- Création automatique du profil à l'inscription (données passées dans les métadonnées).
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username text := lower(trim(coalesce(new.raw_user_meta_data ->> 'username', '')));
  v_type text := coalesce(new.raw_user_meta_data ->> 'account_type', 'client');
  v_problem text;
begin
  v_problem := private.username_problem(v_username);
  if v_problem is not null then
    raise exception 'username_invalid: %', v_problem using errcode = '23514';
  end if;
  if v_type not in ('client', 'provider') then
    v_type := 'client';
  end if;
  if exists (select 1 from public.profiles where username = v_username::extensions.citext) then
    raise exception 'username_taken' using errcode = '23505';
  end if;

  insert into public.profiles (id, username, account_type)
  values (new.id, v_username, v_type::public.account_type);

  insert into public.profile_private (user_id, adult_confirmed_at, terms_accepted_at, terms_version)
  values (
    new.id,
    case when (new.raw_user_meta_data ->> 'adult_confirmed') = 'true' then now() end,
    case when (new.raw_user_meta_data ->> 'terms_version') is not null then now() end,
    new.raw_user_meta_data ->> 'terms_version'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- Activité (comptes inactifs) : appelée à l'ouverture de l'application.
create or replace function public.touch_activity()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles
     set last_active_at = now(),
         inactivity_reminder_sent_at = null,
         hidden_for_inactivity = false
   where id = auth.uid()
     and (last_active_at < now() - interval '1 hour' or hidden_for_inactivity);
end;
$$;

-- Changement de nom d'utilisateur : 1er changement libre, puis 90 jours minimum.
create or replace function public.change_username(p_new_username text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_profile public.profiles := private.require_active_user();
  v_new text := lower(trim(coalesce(p_new_username, '')));
  v_problem text;
  v_next timestamptz;
begin
  if v_new = v_profile.username::text then
    return;
  end if;
  v_problem := public.check_username(v_new);
  if v_problem is not null then
    raise exception '%', v_problem using errcode = '23514';
  end if;
  if v_profile.username_change_count >= 1 and v_profile.username_changed_at is not null then
    v_next := v_profile.username_changed_at + interval '90 days';
    if v_next > now() then
      raise exception 'Vous pourrez de nouveau changer de nom d''utilisateur à partir du %.',
        to_char(v_next at time zone 'Pacific/Tahiti', 'DD/MM/YYYY') using errcode = '42501';
    end if;
  end if;
  update public.profiles
     set username = v_new,
         username_changed_at = now(),
         username_change_count = username_change_count + 1
   where id = v_profile.id;
end;
$$;
