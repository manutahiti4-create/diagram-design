create type public.account_type as enum ('client', 'provider');
create type public.account_status as enum ('active', 'suspended');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username extensions.citext not null unique,
  account_type public.account_type not null,
  avatar_path text,
  commune_id smallint references public.communes (id),
  status public.account_status not null default 'active',
  is_hidden boolean not null default false,
  hidden_reason text,
  username_changed_at timestamptz,
  username_change_count integer not null default 0,
  last_active_at timestamptz not null default now(),
  inactivity_reminder_sent_at timestamptz,
  hidden_for_inactivity boolean not null default false,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (username::text ~ '^[a-z0-9][a-z0-9_.-]{2,23}$'),
  constraint profiles_avatar_path check (avatar_path is null or avatar_path like (id::text || '/%'))
);
create trigger profiles_updated_at before update on public.profiles
  for each row execute function private.set_updated_at();

